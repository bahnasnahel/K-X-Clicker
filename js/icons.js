export function icon(name, size = 24) {
  const m = MAPS[name] || MAPS.tasks;
  let r = "";
  m.forEach((row, y) => [...row].forEach((c, x) => { if (c === "#") r += `<rect x="${x}" y="${y}" width="1" height="1"/>`; }));
  return `<svg class="ico" viewBox="0 0 8 8" width="${size}" height="${size}" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true">${r}</svg>`;
}
